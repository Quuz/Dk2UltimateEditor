"""Read-only projections of inspected first-person arithmetic, not full input/rendering."""
from pathlib import Path
import json
from functools import lru_cache

FIELDS={0x107B:('SniperZoomMultiplier',4),0xDBC:('WaddleScale',4),0xDC0:('OscillateScale',4),0xD3D:('WalkCycleScale',1)}
def checked(v,bits):
    if type(v) is not int or not 0<=v<1<<bits:raise ValueError(f'Expected unsigned{bits} integer')
    return v
def u32(v):return v&0xFFFFFFFF
def s32(v):return (v+0x80000000)%0x100000000-0x80000000
def trunc(v,d):return v//d if v>=0 else -((-v)//d)
@lru_cache(maxsize=1)
def sine_table():return json.loads((Path(__file__).parent/'phase25-native-sine-table.json').read_text())['values']

def motion_terms(raw_waddle,raw_oscillate,raw_cycle,phase,half_oscillation=False):
    """Ungated terms. Full caller status/input/terrain gates are deliberately outside this API."""
    checked(raw_waddle,32);checked(raw_oscillate,32);checked(raw_cycle,8);checked(phase,32)
    if type(half_oscillation) is not bool:raise ValueError('Expected bool')
    p=u32(raw_cycle*phase);wi=((u32(p<<7)>>2)&2047);oi=((u32(p<<8)>>2)&2047)
    table=sine_table();wp=s32(table[wi]*raw_waddle);op=s32(table[oi]*raw_oscillate)
    oscillate=trunc(trunc(op,128),4096)
    if half_oscillation:oscillate=trunc(oscillate,2)
    return dict(waddle_index=wi,oscillate_index=oi,
        input_waddle=trunc(trunc(wp,512),4096),action80_waddle=trunc(trunc(wp,4096),4096),oscillate=oscillate)

def sniper_commands(raw_zoom,level,slots,slot_count,camera_base,state_flags,player_tag=1):
    """Commands generated by 40FDF0 after caller has supplied a possessed creature.

    Slot count is the runtime byte. At most physical slots0..2 are queried.
    The getter fallback is the native initialized zero slot, even if count<3.
    No SpecialAbility enum or spell-definition success test exists in this body.
    """
    checked(raw_zoom,32);checked(level,8);checked(slot_count,8);checked(camera_base,32);checked(state_flags,32);checked(player_tag,16)
    if len(slots)!=3:raise ValueError('Expected three (spellId, levelAvailable) pairs')
    for spell,available in slots:checked(spell,8);checked(available,8)
    factor=raw_zoom>>12;selected=None
    if factor>1:
        for i,(spell,available) in enumerate(slots):
            if i<slot_count and available<=level and spell:
                selected=spell;break
    commands=[]
    if selected is not None:
        active=bool(state_flags&0x80000000)
        target=camera_base if active else u32(camera_base*factor)
        commands=[dict(type=0xE,value=target,second=300,third=0,player_tag=player_tag),
                  dict(type=0x27,value=0 if active else 1,second=0,third=0,player_tag=player_tag)]
    return dict(integer_factor=factor,selected_spell=selected,commands=commands)

def sniper_flag_after_action(state_flags,action_value,possessed_creature_present=True):
    checked(state_flags,32);checked(action_value,32)
    return (state_flags&0x7FFFFFFF)|((action_value&1)<<31) if possessed_creature_present else state_flags

def record_view(record):
    check_record(record)
    values={name:int.from_bytes(record[off:off+width],'little') for off,(name,width) in FIELDS.items()}
    values['sniper_integer_factor']=values['SniperZoomMultiplier']>>12
    values['sniper_multiplier_gate']=values['sniper_integer_factor']>1
    return values
def check_record(record):
    if not isinstance(record,(bytes,bytearray)) or len(record) not in [5449,5537]:raise ValueError('Expected Creatures record of5449 or5537 bytes')
def patch_raw(record,offset,value):
    check_record(record)
    if offset not in FIELDS:raise ValueError('Unsupported field')
    width=FIELDS[offset][1];checked(value,8*width)
    return bytes(record[:offset])+value.to_bytes(width,'little')+bytes(record[offset+width:])
