def profile(sha):
    if sha not in PROFILES:raise ValueError('ExpectedexactinspectedSHA')
    return PROFILES[sha]
def intermediate(raw,prior=None):
    raw=sized(raw,616,'Doorrecord');b=bytearray(bytes(732) if prior is None else sized(prior,732,'Doorintermediate'))
    for pres,src,dst,n in CONVERT+RESOURCES:struct.pack_into('<I',b,pres,1);b[dst:dst+n]=raw[src:src+n]
    for pres,src,dst in [(0,0,0x74),(8,0x248,0x2BC)]:struct.pack_into('<I',b,pres,1);b[dst:dst+32]=string32(raw[src:src+32])
    struct.pack_into('<I',b,0x70,1);struct.pack_into('<I',b,0x29C,struct.unpack_from('<I',b,0x29C)[0]|struct.unpack_from('<I',raw,0x228)[0])
    return bytes(b)
def sound_requested(mid,sha,gate):return bool(struct.unpack_from('<I',sized(mid,732,'Doorintermediate'),8)[0] and (profile(sha)['gate'] is None or not u32(gate)))
def definition(mid,prior,sha,gate=0,sound_token=0):
    mid=sized(mid,732,'Doorintermediate');b=bytearray(sized(prior,181,'Doordefinition'));p=profile(sha);u32(gate);u32(sound_token)
    if p['gate'] is None or not gate:struct.pack_into('<I',b,0x87,sum(mid))
    for pres,src,dst,n in LOAD:
        if struct.unpack_from('<I',mid,pres)[0]:b[dst:dst+n]=mid[src:src+n]
    if sound_requested(mid,sha,gate):struct.pack_into('<I',b,0xA9,sound_token)
    return bytes(b)

def patch_research_time(raw, value):
    """Patch baseline ResearchTime WORD224 without normalizing other bytes."""
    raw = sized(raw, 616, 'Door record')
    if type(value) is not int or not 0 <= value <= 65535:
        raise ValueError('Expected unsigned WORD')
    return raw[:0x224] + value.to_bytes(2, 'little') + raw[0x226:]
