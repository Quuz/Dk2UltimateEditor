/// <summary>Private ten-value page context. No document or writer is retained.
/// Caller must provide a complete, ordered effective source snapshot; this
/// context does not invent defaults or change source/archive provenance.</summary>
public sealed class CreatureLevelModifierDraft : IDisposable
{
    private readonly Dictionary<CreatureLevelModifierKey,uint> original=[];
    private readonly Dictionary<CreatureLevelModifierKey,short> values=[];
    private bool closed;
    public CreatureLevelModifierDraft(IEnumerable<CreatureLevelModifierRecord> source)
    {
        ArgumentNullException.ThrowIfNull(source);
        foreach(var row in source)
        {
            if(!CreatureLevelModifierControls.HasStatistic(row.Statistic)||!(row.IsDocumentedLevelKey||row.IsObservedPossessionKey))continue;
            var key=new CreatureLevelModifierKey(row.RecordType,row.Statistic,row.Level);
            // The official loader assigns a SHORT for each occurrence in file
            // order. Duplicate source bytes are not rewritten by this context.
            original[key]=row.PercentBits;values[key]=unchecked((short)row.PercentBits);
        }
        foreach(var stat in CreatureLevelModifierControls.Statistics)
        {
            var id=uint.Parse(stat.Value,System.Globalization.CultureInfo.InvariantCulture);
            foreach(var key in Keys(id))if(!values.ContainsKey(key))throw new InvalidDataException($"Missing effective level modifier: {key}.");
        }
    }
    public uint SelectedStatistic {get;private set;}
    public bool IsClosed=>closed;
    public CreatureLevelModifierValues Current
    {
        get
        {
            Alive();var id=SelectedStatistic;
            return new(Array.AsReadOnly(Enumerable.Range(2,9).Select(level=>(int)values[new(0x41,id,(uint)level)]).ToArray()),values[new(0xE0,id,10)]);
        }
    }
    public IReadOnlyList<CreatureLevelModifierChange> Changes
    {
        get
        {
            Alive();return Array.AsReadOnly(values.Where(p=>p.Value!=unchecked((short)original[p.Key]))
                .OrderBy(p=>p.Key.Statistic).ThenBy(p=>p.Key.RecordType).ThenBy(p=>p.Key.Level)
                .Select(p=>new CreatureLevelModifierChange(p.Key,original[p.Key],p.Value)).ToArray());
        }
    }
    public void Store(CreatureLevelModifierValues input)
    {
        Alive();ArgumentNullException.ThrowIfNull(input);ArgumentNullException.ThrowIfNull(input.Levels);
        if(input.Levels.Count!=9)throw new ArgumentException("Provide all nine level percentages.",nameof(input));
        var copy=input.Levels.Concat(new[]{input.FirstPerson}).ToArray();
        if(copy.Any(v=>v<CreatureLevelModifierControls.Minimum||v>CreatureLevelModifierControls.Maximum))
            throw new ArgumentOutOfRangeException(nameof(input),"Official level percentages range from -10000 to 10000.");
        var keys=Keys(SelectedStatistic).ToArray();
        for(var i=0;i<keys.Length;i++)values[keys[i]]=(short)copy[i];
    }
    public void SelectStatistic(uint id,CreatureLevelModifierValues current)
    {
        Alive();if(!CreatureLevelModifierControls.HasStatistic(id))throw new ArgumentOutOfRangeException(nameof(id));
        Store(current);SelectedStatistic=id;
    }
    internal IReadOnlyList<KeyValuePair<CreatureLevelModifierKey,short>> SnapshotValues()
    {Alive();return Array.AsReadOnly(values.ToArray());}
    private static IEnumerable<CreatureLevelModifierKey> Keys(uint id)
    {
        foreach(var level in Enumerable.Range(2,9))yield return new(0x41,id,(uint)level);
        yield return new(0xE0,id,10);
    }
    private void Alive(){if(closed)throw new ObjectDisposedException(nameof(CreatureLevelModifierDraft));}
    public void Dispose()=>closed=true;
}
